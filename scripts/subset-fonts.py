#!/usr/bin/env python3
"""Split Inter into per-script WOFF2 subsets and write their @font-face rules.

Browsers only download the subsets whose unicode-range matches text on the
page, so most visits fetch the Latin file alone. Every glyph, weight and
OpenType feature of the source font is kept in exactly one subset; to use a
new weight or feature, update the CSS, not this script.

Requires fonttools and brotli (pip install fonttools brotli). The generated
files are committed, so builds do not need Python. Re-run after replacing the
source font:

    python3 scripts/subset-fonts.py
"""

from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
source = root / "font-sources/Inter-VariableFont_opsz,wght.ttf"
output_dir = root / "www/font/Inter"
css_path = root / "www/css/foundation/fonts-inter.css"

# Ranges follow the Google Fonts subsets for Inter. "symbols" collects every
# remaining code point in the font so nothing falls back to a system font.
# Symbols rendered by the UI (≤, the ⌘ search hint and the ▲▼ sort arrows) are
# added to "latin" so the larger symbols subset is not downloaded for them.
subsets = {
    "latin": "0000-00FF,0131,0152-0153,02BB-02BC,02C6,02DA,02DC,0304,0308,0329,"
             "2000-206F,20AC,2122,2191,2193,2212,2215,2264,2318,25B2,25BC,FEFF,FFFD",
    "latin-ext": "0100-02BA,02BD-02C5,02C7-02CC,02CE-02D7,02DD-02FF,0304,0308,0329,"
                 "1D00-1DBF,1E00-1E9F,1EA0-1EF9,1EF2-1EFF,2020,20A0-20AB,20AD-20C0,"
                 "2113,2C60-2C7F,A720-A7FF",
    "cyrillic": "0301,0400-052F,1C80-1C8A,20B4,2116,2DE0-2DFF,A640-A69F,FE2E-FE2F",
    "greek": "0370-0377,037A-037F,0384-038A,038C,038E-03A1,03A3-03FF,1F00-1FFF",
}


def parse_ranges(ranges):
    codepoints = set()
    for part in ranges.split(","):
        start, _, end = part.partition("-")
        codepoints.update(range(int(start, 16), int(end or start, 16) + 1))
    return codepoints


def format_ranges(codepoints):
    ranges = []
    for codepoint in sorted(codepoints):
        if ranges and codepoint == ranges[-1][1] + 1:
            ranges[-1][1] = codepoint
        else:
            ranges.append([codepoint, codepoint])
    return ", ".join(f"U+{start:04X}" if start == end else f"U+{start:04X}-{end:04X}"
                     for start, end in ranges)


def main():
    font = TTFont(source)
    available = set(font.getBestCmap())
    weight = next(axis for axis in font["fvar"].axes if axis.axisTag == "wght")
    ranges = {name: parse_ranges(value) & available for name, value in subsets.items()}
    ranges["symbols"] = available - set().union(*ranges.values())

    output_dir.mkdir(parents=True, exist_ok=True)
    rules = []
    for name, codepoints in ranges.items():
        filename = f"inter-{name}.woff2"
        options = subset.Options(layout_features=["*"], name_IDs=["*"],
                                 name_languages=["*"], notdef_outline=True)
        subset_font = TTFont(source)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=codepoints)
        subsetter.subset(subset_font)
        subset_font.flavor = "woff2"
        subset_font.save(output_dir / filename)
        rules.append(f"""/* {name} */
@font-face {{
  font-family: Inter;
  font-style: normal;
  font-weight: {weight.minValue:g} {weight.maxValue:g};
  font-display: swap;
  src: url("font/Inter/{filename}") format("woff2");
  unicode-range: {format_ranges(codepoints)};
}}
""")

    css_path.write_text("/* Generated by scripts/subset-fonts.py. Do not edit by hand. */\n\n"
                        + "\n".join(rules))


if __name__ == "__main__":
    main()
